/**
 * 检查字符串是否包含中文字符
 */
function hasChinese(str) {
  if (!str) return false
  return /[\u4e00-\u9fa5]/.test(str)
}

/**
 * 翻译技能名称
 */
function translateName(enName) {
  if (!enName) return enName
  return TRANSLATIONS[enName] || enName
}

/**
 * 主函数
 */
function main() {
  const skillInfoPath = path.join(__dirname, '../src/data/SKILL_INFO.js')
  const content = fs.readFileSync(skillInfoPath, 'utf8')

  let nameCount = 0

  // 替换 name.cns 字段 - 使用更宽松的正则
  // 匹配模式: 'cns': '任意内容直到下一个未转义的引号'
  let newContent = content.replace(
    /'cns':\s*'((?:[^'\\]|\\.)*)'/g,
    (match, cnsValue) => {
      // 解码转义字符
      const decodedValue = cnsValue.replace(/\\'/g, "'")
      
      // 如果已经有中文，不替换
      if (hasChinese(decodedValue)) {
        return match
      }

      // 尝试翻译
      const translated = translateName(decodedValue)
      if (translated !== decodedValue) {
        nameCount++
        // 编码单引号
        const encodedValue = translated.replace(/'/g, "\\'")
        return `'cns': '${encodedValue}'`
      }
      return match
    }
  )

  // 写回文件
  fs.writeFileSync(skillInfoPath, newContent, 'utf8')

  console.log(`翻译完成！`)
  console.log(`名称翻译: ${nameCount} 个`)
}

main()
