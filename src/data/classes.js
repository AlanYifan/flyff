//武器伤害计算公式
export const WEAPON_DAMAGE_CALCULATION_FORMULA = {
  '1-59': { minMultiplier: 8, maxMultiplier: 8 },
  '60-89': { minMultiplier: 7.5, maxMultiplier: 7.5 },
  '90-104': { minMultiplier: 7, maxMultiplier: 7 },
  '105-119': { minMultiplier: 6.5, maxMultiplier: 6.5 },
  '120-149': { minMultiplier: 6, maxMultiplier: 6 },
  '150-174': { minMultiplier: 5.5, maxMultiplier: 5.5 },
  '175-180': { minMultiplier: 5, maxMultiplier: 5 }
}

// 根据武器等级获取攻击力倍数
export function getWeaponDamageMultiplier(weaponLevel) {
  if (weaponLevel >= 1 && weaponLevel <= 59) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['1-59']
  } else if (weaponLevel >= 60 && weaponLevel <= 89) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['60-89']
  } else if (weaponLevel >= 90 && weaponLevel <= 104) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['90-104']
  } else if (weaponLevel >= 105 && weaponLevel <= 119) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['105-119']
  } else if (weaponLevel >= 120 && weaponLevel <= 149) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['120-149']
  } else if (weaponLevel >= 150 && weaponLevel <= 174) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['150-174']
  } else if (weaponLevel >= 175 && weaponLevel <= 180) {
    return WEAPON_DAMAGE_CALCULATION_FORMULA['175-180']
  } else {
    // 默认返回1-59级的倍数
    return WEAPON_DAMAGE_CALCULATION_FORMULA['1-59']
  }
}

// 应用武器伤害计算公式到武器
export function applyWeaponDamageFormula(weapon) {
  if (!weapon || typeof weapon.level !== 'number') {
    return weapon
  }

  const multiplier = getWeaponDamageMultiplier(weapon.level)

  // 创建武器副本以避免修改原始对象
  const weaponCopy = { ...weapon }

  // 应用倍数计算最终攻击力
  if (typeof weapon.minAttack === 'number') {
    weaponCopy.minAttack = Math.floor(weapon.minAttack * multiplier.minMultiplier)
  }

  if (typeof weapon.maxAttack === 'number') {
    weaponCopy.maxAttack = Math.floor(weapon.maxAttack * multiplier.maxMultiplier)
  }

  return weaponCopy
}

// 获取职业头像路径
export function getClassAvatar(className, gender = 'male') {
  const classData = CLASS_CONFIG[className]

  // 如果是一转基础职业，直接返回配置中的头像
  if (classData) {
    return classData.genderAvatars[gender] || classData.genderAvatars.male
  }

  // 对于二转、三转职业，使用 JOB_TIER_CONFIG 中的图标映射
  const jobConfig = JOB_TIER_CONFIG[className?.toLowerCase()]
  const iconPrefix = jobConfig?.iconPrefix || 'cxz'
  const genderSuffix = gender === 'female' ? 'nv' : 'nan'
  // 三转职业图片命名格式为 {prefix}_{gender}.png（无_icon后缀）
  const iconSuffix = jobConfig?.tier === 3 ? '' : '_icon'
  return `/pt/job_icon/${iconPrefix}_${genderSuffix}${iconSuffix}.png`
}

// 获取职业中文名称
export function getClassName(className) {
  return CLASS_NAME_MAP[className] || '未知职业'
}

// 获取职业详情图片
export function getClassInfoImage(className, gender = 'male') {
  const classData = CLASS_CONFIG[className]
  if (!classData) {
    return '/pt/job_icon/default_icon.png'
  }

  return classData.jobInfoImage[gender] || classData.jobInfoImage.male
}

// 获取性别名称
export function getGenderName(className, gender = 'male') {
  const classData = CLASS_CONFIG[className]
  if (!classData) {
    return gender === 'male' ? '男' : '女'
  }

  return classData.genderNames[gender] || classData.genderNames.male
}

// 获取职业基础属性
export function getClassBaseStats(className) {
  const classData = CLASS_CONFIG[className]
  if (!classData) {
    return CLASS_CONFIG.beginner.baseStats
  }

  return { ...classData.baseStats }
}

// 获取所有职业列表
export function getAllClasses() {
  return Object.values(CLASS_CONFIG).map(cls => ({
    id: cls.id,
    name: cls.name,
    description: cls.description,
    avatar: cls.genderAvatars.male
  }))
}

